// Writes the sqlite schema the native core uses to native/crates/immich_db. Drift needs dart:ui, so
// this runs under `flutter test` (see codegen:native:schema in mise.toml) rather than `dart run`.
import 'dart:io';

import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:immich_mobile/data/db/logger/database.dart';
import 'package:immich_mobile/data/db/main/database.dart';
import 'package:immich_mobile/domain/models/log.model.dart';
import 'package:immich_mobile/domain/models/settings_key.dart';

const _output = '../native/crates/immich_db/src/schema.g.rs';

void main() {
  test('generate native schema', () async {
    final main = Drift(DatabaseConnection(NativeDatabase.memory(), closeStreamsSynchronously: true));
    final logs = DriftLogger.fromExecutor(DatabaseConnection(NativeDatabase.memory(), closeStreamsSynchronously: true));
    final sections = [
      '// generated by mobile/tool/generate_native_schema.dart, do not edit',
      'pub const MAIN_SCHEMA_VERSION: i32 = ${await _version(main)};\npub const LOGS_SCHEMA_VERSION: i32 = ${await _version(logs)};',
      await _table(main, main.settingsEntity, [main.settingsEntity.key, main.settingsEntity.value]),
      await _table(logs, logs.logMessageEntity, [
        logs.logMessageEntity.message,
        logs.logMessageEntity.details,
        logs.logMessageEntity.level,
        logs.logMessageEntity.createdAt,
        logs.logMessageEntity.logger,
        logs.logMessageEntity.stack,
      ]),
      'pub const LOG_LEVEL_SETTING: &str = "${SettingsKey.logLevel.name}";',
      [
        '#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]',
        '#[repr(i64)]',
        'pub enum LogLevel {',
        for (final level in LogLevel.values) '    ${_pascal(level.name)} = ${level.index},',
        '}',
        '',
        'impl LogLevel {',
        '    pub fn from_name(name: &str) -> Option<Self> {',
        '        match name {',
        for (final level in LogLevel.values) '            "${level.name}" => Some(Self::${_pascal(level.name)}),',
        '            _ => None,',
        '        }',
        '    }',
        '}',
      ].join('\n'),
    ];
    await main.close();
    await logs.close();
    await File(_output).writeAsString('${sections.join('\n\n')}\n');
  });
}

Future<int> _version(GeneratedDatabase db) async =>
    (await db.customSelect('PRAGMA user_version').getSingle()).read<int>('user_version');

Future<String> _table(GeneratedDatabase db, TableInfo table, List<GeneratedColumn> columns) async {
  final name = table.actualTableName;
  final ddl = await db
      .customSelect('SELECT sql FROM sqlite_master WHERE name = ?', variables: [Variable.withString(name)])
      .getSingle();
  return [
    'pub mod $name {',
    '    pub const TABLE: &str = "$name";',
    '    pub const SQL: &str = r#"${ddl.read<String>('sql')}"#;',
    for (final column in columns) '    pub const ${column.name.toUpperCase()}: &str = "${column.name}";',
    '    pub const COLUMNS: &[&str] = &[${columns.map((column) => column.name.toUpperCase()).join(', ')}];',
    '}',
  ].join('\n');
}

String _pascal(String name) => '${name[0].toUpperCase()}${name.substring(1)}';
