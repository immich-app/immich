#!/usr/bin/env bash
# =============================================================================
# immich-go CONTAINER installer — works with BOTH Docker and Podman.
# Self-contained: needs only this folder (Dockerfile + docker-compose.yml).
#
# Usage:
#   ./scripts/install-container.sh              # auto-detect docker|podman
#   ./scripts/install-container.sh --docker     # force docker
#   ./scripts/install-container.sh --podman     # force podman
#   ./scripts/install-container.sh --arch amd64 # build for x86 instead of arm64
#   ./scripts/install-container.sh --admin-email me@x.com --admin-password 'S3cret!'
#   ./scripts/install-container.sh --data-vol my-volume-name
#   ./scripts/install-container.sh --uninstall  # stop+remove containers (volume kept)
#
# First run builds the image locally (multi-stage, static, ~25MB final image).
# Data persists in the named volume "immich-go-data" (override with --data-vol).
# =============================================================================
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
ENGINE=""            # docker | podman
ARCH="arm64"         # ODROID-C2 default; use amd64 on x86 hosts
ADMIN_EMAIL="admin@example.com"
ADMIN_PASSWORD=""
PORT="2283"
DATA_VOL="immich-go-data"
UNINSTALL=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --docker)        ENGINE="docker"; shift ;;
    --podman)        ENGINE="podman"; shift ;;
    --arch)          ARCH="$2"; shift 2 ;;
    --admin-email)   ADMIN_EMAIL="$2"; shift 2 ;;
    --admin-password) ADMIN_PASSWORD="$2"; shift 2 ;;
    --port)          PORT="$2"; shift 2 ;;
    --data-vol)      DATA_VOL="$2"; shift 2 ;;
    --uninstall)     UNINSTALL=true; shift ;;
    -h|--help)       sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown flag: $1 (see --help)"; exit 1 ;;
  esac
done

log() { printf '\e[1;36m[immich-go]\e[0m %s\n' "$*"; }
die() { printf '\e[1;31mERROR:\e[0m %s\n' "$*" >&2; exit 1; }

# --------------------------- engine detection ---------------------------------
if [[ -z "$ENGINE" ]]; then
  if command -v docker >/dev/null 2>&1; then ENGINE="docker"
  elif command -v podman >/dev/null 2>&1; then ENGINE="podman"
  else die "Neither docker nor podman found. Install one first:
     DietPi/Debian:  curl -fsSL https://get.docker.com | sh
     Podman:         apt install -y podman podman-compose   (or: dnf install podman)"
  fi
fi
command -v "$ENGINE" >/dev/null 2>&1 || die "engine '$ENGINE' not installed"

# compose: prefer plugin (`docker compose`), fallback podman-compose / docker-compose
compose() {
  if "$ENGINE" compose version >/dev/null 2>&1; then "$ENGINE" compose "$@"
  elif command -v podman-compose >/dev/null 2>&1 && [[ $ENGINE == podman ]]; then podman-compose "$@"
  elif command -v docker-compose >/dev/null 2>&1; then docker-compose "$@"
  else
    # No compose available → plain run fallback defined below.
    return 127
  fi
}

IMAGE_NAME="immich-go:latest"

if $UNINSTALL; then
  log "Uninstalling ($ENGINE)... data volume '$DATA_VOL' is KEPT."
  compose -f "$HERE/docker-compose.yml" down 2>/dev/null || \
    { "$ENGINE" rm -f immich-go-server 2>/dev/null || true; }
  log "To delete all data too: $ENGINE volume rm $DATA_VOL"
  exit 0
fi

# --------------------------- .env preparation ---------------------------------
ENV_FILE="$HERE/.env"
JWT_SECRET=""
if [[ -f "$ENV_FILE" ]] && grep -q '^IMMICHGO_JWT_SECRET=' "$ENV_FILE"; then
  JWT_SECRET="$(grep -m1 '^IMMICHGO_JWT_SECRET=' "$ENV_FILE" | cut -d= -f2-)"
  [[ "$JWT_SECRET" == CHANGE_ME* ]] && JWT_SECRET=""
fi
[[ -z "$JWT_SECRET" ]] && JWT_SECRET="$( (command -v openssl >/dev/null && openssl rand -hex 32) || head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"

if [[ -z "$ADMIN_PASSWORD" ]]; then
  if [[ -f "$ENV_FILE" ]] && grep -q '^IMMICHGO_ADMIN_PASSWORD=' "$ENV_FILE"; then
    ADMIN_PASSWORD="$(grep -m1 '^IMMICHGO_ADMIN_PASSWORD=' "$ENV_FILE" | cut -d= -f2-)"
  fi
fi
if [[ -z "$ADMIN_PASSWORD" ]]; then
  ADMIN_PASSWORD="$(head -c 12 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 16)"
  GEN_PASS=true
else
  GEN_PASS=false
fi

cat > "$ENV_FILE" <<EOF
# Generated by install-container.sh on $(date -u +%F\ %TZ) — safe to edit, then re-run.
IMMICHGO_JWT_SECRET=$JWT_SECRET
IMMICHGO_ADMIN_EMAIL=$ADMIN_EMAIL
IMMICHGO_ADMIN_PASSWORD=$ADMIN_PASSWORD
IMMICHGO_PORT=$PORT
LEGACY_DSN=
LEGACY_LIBRARY_HOST_PATH=./empty-library
EOF
chmod 600 "$ENV_FILE"
log "Wrote config to $ENV_FILE"

mkdir -p "$HERE/empty-library"   # placeholder mount so compose never fails

# --------------------------- build image --------------------------------------
log "Building image $IMAGE_NAME for linux/$ARCH ($ENGINE)..."
if ! compose -f "$HERE/docker-compose.yml" build server >/dev/null 2>&1; then
  # no compose plugin: build directly
  "$ENGINE" build --platform "linux/$ARCH" -t "$IMAGE_NAME" "$HERE" \
    || die "image build failed — check the output above"
fi
log "Image ready."

# --------------------------- start container ----------------------------------
log "Starting server (port $PORT, volume $DATA_VOL)..."
if ! compose -f "$HERE/docker-compose.yml" up -d server; then
  # -------- compose-less fallback: single `run` with explicit flags ----------
  log "Compose unavailable — falling back to plain $ENGINE run"
  "$ENGINE" volume create "$DATA_VOL" >/dev/null 2>&1 || true
  "$ENGINE" rm -f immich-go-server >/dev/null 2>&1 || true
  "$ENGINE" run -d --name immich-go-server --restart unless-stopped \
    -p "${PORT}:2283" \
    -v "${DATA_VOL}:/data" \
    -e IMMICHGO_JWT_SECRET="${JWT_SECRET}" \
    -e IMMICHGO_ADMIN_EMAIL="${ADMIN_EMAIL}" \
    -e IMMICHGO_ADMIN_PASSWORD="${ADMIN_PASSWORD}" \
    -e IMMICHGO_DATA_DIR=/data \
    -e GIN_MODE=release \
    --memory 600m \
    "$IMAGE_NAME"
fi

sleep 2
HEALTH_OK=false
for i in 1 2 3 4 5; do
  if "$ENGINE" exec immich-go-server wget -qO- http://127.0.0.1:2283/api/health >/dev/null 2>&1 \
     || (command -v curl >/dev/null && curl -fsS "http://127.0.0.1:${PORT}/api/health" >/dev/null 2>&1); then
    HEALTH_OK=true; break
  fi
  sleep 2
done

IP="$(hostname -I 2>/dev/null | awk '{print $1}' || echo 127.0.0.1)"
echo
log "=========================================================="
$HEALTH_OK && log "Server is UP and healthy ✅" || log "WARN: health check failed — inspect logs"
log "  App server URL : http://${IP}:${PORT}/api"
log "  Admin email    : ${ADMIN_EMAIL}"
$GEN_PASS && log "  Admin password : ${ADMIN_PASSWORD}   <-- SAVE THIS NOW"
log "  Logs           : $ENGINE logs -f immich-go-server"
log "  Legacy import  : $HERE/scripts/run-migrate.sh  (see README section 7)"
log "=========================================================="
